from datetime import datetime, timezone
from sqlalchemy import Column, Integer, String, Boolean, DateTime, ForeignKey, Text
from database import Base


def utcnow():
    return datetime.now(timezone.utc)


class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    email = Column(String, unique=True, index=True, nullable=False)
    password_hash = Column(String, nullable=False)
    created_at = Column(DateTime, default=utcnow)


class LoginEvent(Base):
    __tablename__ = "login_events"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=True)  # null if email doesn't exist
    email_attempted = Column(String, nullable=False)
    ip_prefix = Column(String)        # truncated network, not the full IP
    ua_summary = Column(String)       # e.g. "Chrome / Windows"
    device_id = Column(String)        # random ID generated by the browser
    country = Column(String)          # country code only
    success = Column(Boolean, nullable=False)
    failure_reason = Column(String)
    risk_score = Column(Integer)
    decision = Column(String)         # allow / step_up / restrict
    reasons_json = Column(Text)
    created_at = Column(DateTime, default=utcnow, index=True)


class KnownDevice(Base):
    __tablename__ = "known_devices"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    device_id = Column(String, nullable=False)
    ua_summary = Column(String)
    trusted = Column(Boolean, default=False, nullable=False)
    first_seen_at = Column(DateTime, default=utcnow)
    last_seen_at = Column(DateTime, default=utcnow)


class StepUpChallenge(Base):
    __tablename__ = "step_up_challenges"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    device_id = Column(String)
    code_hash = Column(String, nullable=False)   # the code itself is never stored
    attempts = Column(Integer, default=0, nullable=False)
    used = Column(Boolean, default=False, nullable=False)
    risk_score = Column(Integer)
    reasons_json = Column(Text)
    created_at = Column(DateTime, default=utcnow)
    expires_at = Column(DateTime, nullable=False)

